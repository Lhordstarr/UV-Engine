def list_models(vram_available=None, type_filter=None, query=None):
    out = []
    for m in MODELS:
        est = estimate_vram(m["id"], m["default_resolution"][0], m["default_resolution"][1], m["default_frames"])
        m2 = dict(m)
        m2["vram_estimate_gb"] = est
        m2["download_url"] = f"https://huggingface.co/{m['source']}"
        m2["supports_real_generation"] = bool(m.get("diffusers_repo"))
        if vram_available is not None:
            m2["fits"] = est <= vram_available * 0.92
        if type_filter and m["type"] != type_filter:
            continue
        if query:
            q = query.lower()
            if q not in m["name"].lower() and q not in m["family"].lower() and q not in " ".join(m["tags"]).lower():
                continue
        out.append(m2)
    return out

def get_model(mid):
    for m in MODELS:
        if m["id"] == mid:
            m2 = dict(m)
            m2["vram_estimate_gb"] = estimate_vram(m["id"], m["default_resolution"][0], m["default_resolution"][1], m["default_frames"])
            m2["download_url"] = f"https://huggingface.co/{m['source']}"
            m2["supports_real_generation"] = bool(m.get("diffusers_repo"))
            return m2
    return None
